// Writes THIRD-PARTY-NOTICES.txt: the licence of everything the Windows build
// ships that isn't Orbit's own code (Rust crates, npm packages bundled into
// the page, fonts, libmpv/FFmpeg, yt-dlp), with each licence text once.
// Usage: pnpm run notices (needs the crates fetched, i.e. a cargo build or
// `cargo fetch`, and node_modules installed; works offline).
//
// MIT, BSD and Apache-2.0 ask for their notices to travel with binaries, the
// OFL with fonts, and the LGPL with libmpv, so the file is bundled as a
// resource (tauri.conf.json) and opened from Settings → About Orbit.
import { execFileSync, execSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'THIRD-PARTY-NOTICES.txt');
/** Only Windows is released for now (see docs/RELEASING.md). */
const TARGET = 'x86_64-pc-windows-msvc';
const LICENCE_FILE = /^(licen[cs]e|copying|notice|unlicen[cs]e|copyright)([-_.].*)?$/i;

/** Licence and notice files at the top of a package's folder, sorted for a stable output. */
function licenceFiles(dir) {
  return readdirSync(dir)
    .filter((name) => LICENCE_FILE.test(name) && statSync(join(dir, name)).isFile())
    .sort()
    .map((name) => ({ name, text: readFileSync(join(dir, name), 'utf8') }));
}

const normalise = (text) => text.replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '').trim();

// ---- Rust crates in the release build ------------------------------------

function rustCrates() {
  const json = execFileSync('cargo', ['metadata', '--format-version', '1', '--manifest-path', join(root, 'src-tauri', 'Cargo.toml'), '--filter-platform', TARGET, '--offline'], {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'inherit'],
  });
  const meta = JSON.parse(json);
  const packages = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  // Normal dependencies only: dev-dependencies never ship, and build scripts run at compile time.
  const seen = new Set();
  const queue = [meta.resolve.root];
  while (queue.length) {
    const id = queue.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      if (dep.dep_kinds.some((k) => k.kind === null)) queue.push(dep.pkg);
    }
  }
  seen.delete(meta.resolve.root);
  return [...seen].map((id) => {
    const p = packages.get(id);
    return {
      name: p.name,
      version: p.version,
      licence: p.license ?? (p.license_file ? `see ${p.license_file}` : 'unknown'),
      authors: p.authors ?? [],
      url: p.repository ?? p.homepage ?? `https://crates.io/crates/${p.name}`,
      files: licenceFiles(dirname(p.manifest_path)),
    };
  });
}

// ---- npm packages bundled into the page ----------------------------------

function npmPackages() {
  // A fixed command line through the shell, so pnpm.cmd is found on Windows.
  const json = execSync('pnpm licenses list --prod --json', { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
  // `--prod` still lists a dev dependency that a runtime package names as an
  // optional peer (TypeScript, through valibot); it's never in the page.
  const { dependencies = {}, devDependencies = {} } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const devOnly = (name) => name in devDependencies && !(name in dependencies);
  return Object.values(JSON.parse(json))
    .flat()
    .filter((p) => !devOnly(p.name))
    .flatMap((p) =>
      p.versions.map((version, i) => ({
        name: p.name,
        version,
        licence: p.license,
        authors: p.author ? [p.author] : [],
        url: p.homepage ?? `https://www.npmjs.com/package/${p.name}`,
        files: licenceFiles(p.paths[i] ?? p.paths[0]),
      })),
    );
}

